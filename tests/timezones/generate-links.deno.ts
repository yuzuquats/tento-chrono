/**
 * Generates `chrono/timezone-links.ts` (`TIMEZONE_LINKS`, the table behind
 * `TimezoneRegion.legacyNames`) from tzdata's `backward` file and the set of
 * zones the zone service serves, both checked in beside this script:
 *
 * - `tzdata-2024b-backward`: tzdata 2024b's `backward` file, as released in
 *   https://data.iana.org/time-zones/releases/tzdata2024b.tar.gz
 *   (sha256 70e754db126a8d0db3d16d6b4cb5f7ec1e04d5f261255e4558a67fe92d39e550).
 * - `2024b-served.json`: the names the zone service answers 200 for
 *   (`https://static.lona.so/timezones/2024b/1900_2050/<Area~City>.json`):
 *   every geographic `Zone` of tzdata 2024b (311); no `Etc/*` zone. Probed
 *   name by name on 2026-10-07.
 *
 * Each `Link TARGET NAME` maps NAME to the served zone its target chain ends
 * at (a 2022+ merge such as Europe/Amsterdam -> Europe/Brussels, a rename
 * such as Asia/Calcutta -> Asia/Kolkata, a chain such as Pacific/Truk ->
 * Pacific/Port_Moresby); a link whose chain ends at no served zone (the
 * `Etc/*` and `GMT` spellings, which `UTC` covers) is left out.
 *
 *   deno run --allow-read --allow-write tento-chrono/tests/timezones/generate-links.deno.ts
 *
 * `tests/test_tz_links.deno.test.ts` fails when the checked-in table is not
 * this script's output.
 */

/** NAME -> TARGET for every `Link TARGET NAME` line of a tzdata source. */
export function linksOf(source: string): Map<string, string> {
  const links = new Map<string, string>();
  for (const line of source.split("\n")) {
    const fields = line.replace(/#.*/, "").trim().split(/\s+/);
    if (fields[0] !== "Link" || fields.length < 3) continue;
    links.set(fields[2]!, fields[1]!);
  }
  return links;
}

/** Every link name mapped to the served zone its chain ends at, sorted by name; links reaching none are left out. */
export function servedLinks(links: ReadonlyMap<string, string>, served: ReadonlySet<string>): [string, string][] {
  const out: [string, string][] = [];
  for (const name of [...links.keys()].sort()) {
    let target = links.get(name)!;
    for (let hops = 0; !served.has(target) && links.has(target) && hops < 8; hops++) target = links.get(target)!;
    if (served.has(target) && target !== name) out.push([name, target]);
  }
  return out;
}

/** The generated module's text for `entries`. */
export function render(entries: readonly (readonly [string, string])[]): string {
  return [
    "// Generated by tento-chrono/tests/timezones/generate-links.deno.ts from tzdata 2024b `backward`",
    "// and the zone service's served set (tests/timezones/2024b-served.json). Do not edit; re-run it.",
    'import type { Tzname } from "./timezone.ts";',
    "",
    "/**",
    " * Every tzdata 2024b `backward` link name mapped to the served zone its link",
    " * chain ends at (`TimezoneRegion.legacyNames`): the zone service serves",
    " * current zone names only.",
    " */",
    "export const TIMEZONE_LINKS: ReadonlyMap<Tzname, Tzname> = new Map(",
    "  ([",
    ...entries.map(([name, zone]) => `    [${JSON.stringify(name)}, ${JSON.stringify(zone)}],`),
    "  ] as const).map(([link, zone]) => [link as Tzname, zone as Tzname]),",
    ");",
    "",
  ].join("\n");
}

/** The table as the checked-in inputs give it. */
export async function generate(): Promise<string> {
  const backward = await Deno.readTextFile(new URL("./tzdata-2024b-backward", import.meta.url));
  const served = new Set<string>(JSON.parse(await Deno.readTextFile(new URL("./2024b-served.json", import.meta.url))));
  return render(servedLinks(linksOf(backward), served));
}

export const OUTPUT = new URL("../../chrono/timezone-links.ts", import.meta.url);

if (import.meta.main) {
  await Deno.writeTextFile(OUTPUT, await generate());
  console.log(`wrote ${OUTPUT.pathname}`);
}
