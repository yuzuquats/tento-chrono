"""Generate the bundled 32-bit TZif blocks for the pinned dateutil profile."""

import argparse
import base64
import json
from pathlib import Path
import struct

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("zoneinfo", type=Path, help="Compiled IANA zoneinfo directory")
args = parser.parse_args()
root = args.zoneinfo

version_line, *rules = (root / "tzdata.zi").read_text().splitlines()
assert version_line == "# version 2026e", version_line

blocks: dict[bytes, int] = {}
names: dict[str, int] = {}
for path in sorted(root.rglob("*")):
    name = path.relative_to(root).as_posix()
    if name.startswith(("posix/", "right/")) or name in ("localtime", "posixrules"):
        continue
    if not path.is_file():
        continue
    raw = path.read_bytes()
    if not raw.startswith(b"TZif"):
        continue
    utc_flags, standard_flags, leaps, times, types, abbr_bytes = struct.unpack(
        ">6I", raw[20:44]
    )
    end = 44 + 5 * times + 6 * types + abbr_bytes + 8 * leaps + standard_flags + utc_flags
    assert len(raw) >= end, name
    names[name] = blocks.setdefault(raw[:end], len(blocks))

# Some distributions package the IANA legacy links separately from the TZif files.
for rule in rules:
    fields = rule.split()
    if fields and fields[0] == "L":
        _, target, alias = fields
        names.setdefault(alias, names[target])

print("// Generated by tests/timezones/generate-dateutil-tzif.py from IANA tzdata 2026e.")
print("// Dateutil 2.8.2 reads only the 32-bit block from each file.")
print("const names: Readonly<Record<string, number>> = {")
for name, block in sorted(names.items()):
    print(f"  {json.dumps(name)}: {block},")
print("};\n\nconst blocks = [")
for block in blocks:
    print(f'  "{base64.b64encode(block).decode("ascii")}",')
print('''];\n
const foldedNames = new Set(
  Object.keys(names).map((name) => name.toLowerCase()),
);

export function isBundledDateutilNameIgnoringCase(name: string): boolean {
  return foldedNames.has(name.toLowerCase());
}

export function bundledDateutilTzif(name: string): Uint8Array | undefined {
  if (!Object.hasOwn(names, name)) return undefined;
  return Uint8Array.from(
    atob(blocks[names[name]]),
    (byte) => byte.charCodeAt(0),
  );
}''')
